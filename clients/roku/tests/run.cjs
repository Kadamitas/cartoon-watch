const { spawnSync } = require('node:child_process')
const path = require('node:path')
const fs = require('node:fs')
require('./layout.cjs')
const root = path.resolve(__dirname, '..')
const interpreter = require.resolve('@rokucommunity/brs/bin/cli.js')
function run(source, test, marker) {
  const result = spawnSync(process.execPath, [interpreter, '--root', root, source, path.join(__dirname, test)], { encoding: 'utf8', cwd: root })
  process.stdout.write(result.stdout || '')
  process.stderr.write(result.stderr || '')
  if (result.status !== 0 || !result.stdout.includes(marker) || result.stdout.includes('FAIL:')) process.exit(1)
}
const source = path.join(root, 'components/CartoonWatch.brs')
run(source, 'transport.brs', 'ROKU_LOGIC_PASS')
const work = path.resolve(root, '../../work')
fs.mkdirSync(work, { recursive: true })
const fixture = path.join(fs.mkdtempSync(path.join(work, 'roku-discovery-')), 'CartoonWatch.brs')
fs.writeFileSync(fixture, fs.readFileSync(source, 'utf8').replace(/\bCreateObject\(/g, 'mockCreateObject('))
run(fixture, 'discovery.brs', 'ROKU_DISCOVERY_PASS')
